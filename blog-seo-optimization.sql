-- Blog SEO / CTR optimisation: new meta titles and meta descriptions for every
-- published blog post, plus the cover-image alt text where the image is known.
--
-- HOW TO RUN: Hostinger hPanel -> phpMyAdmin -> your database -> SQL tab ->
-- paste this whole file -> Go. It is safe to run more than once, and any slug
-- below that does not exist in your database is simply skipped.
--
-- Titles are 48-60 characters and now print WITHOUT the " | W&S Digital
-- Marketing" suffix on blog posts (blog-post.php), so the whole title fits in
-- search results. Descriptions are 115-141 characters (under the ~155 limit).
-- Updating a row also refreshes its updated_at, which feeds the sitemap
-- <lastmod> and the article's dateModified, a recrawl signal for Google.
--
-- Schema (BlogPosting + FAQPage + Breadcrumb), the FAQ markup, heading order
-- and image tags are generated by the website code from each post itself, so
-- nothing else needs to be pasted anywhere.

-- 1. Make sure the image_alt column exists (added by seo-dashboard-migration.sql).
SET @col_exists = (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'blog_posts' AND COLUMN_NAME = 'image_alt'
);
SET @sql = IF(@col_exists = 0,
    'ALTER TABLE blog_posts ADD COLUMN image_alt VARCHAR(255) NOT NULL DEFAULT ''''',
    'SELECT ''image_alt already exists, skipping'''
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

